create table if not exists public.admin_expenses (
  id bigint generated by default as identity primary key,
  expense_date date not null default (now() at time zone 'Asia/Dhaka')::date,
  category text not null,
  description text not null,
  amount numeric(12,2) not null check (amount > 0),
  payment_method text not null default 'cash',
  reference text,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);
create index if not exists admin_expenses_expense_date_idx on public.admin_expenses (expense_date desc);
alter table public.admin_expenses enable row level security;
drop policy if exists owner_admin_read_expenses on public.admin_expenses;
create policy owner_admin_read_expenses on public.admin_expenses for select to authenticated
using (exists (select 1 from public.user_roles ur where ur.user_id = (select auth.uid()) and ur.role = 'owner_admin'));
drop policy if exists owner_admin_insert_expenses on public.admin_expenses;
create policy owner_admin_insert_expenses on public.admin_expenses for insert to authenticated
with check (exists (select 1 from public.user_roles ur where ur.user_id = (select auth.uid()) and ur.role = 'owner_admin') and created_by = (select auth.uid()));
drop policy if exists owner_admin_update_expenses on public.admin_expenses;
create policy owner_admin_update_expenses on public.admin_expenses for update to authenticated
using (exists (select 1 from public.user_roles ur where ur.user_id = (select auth.uid()) and ur.role = 'owner_admin'))
with check (exists (select 1 from public.user_roles ur where ur.user_id = (select auth.uid()) and ur.role = 'owner_admin'));
drop policy if exists owner_admin_delete_expenses on public.admin_expenses;
create policy owner_admin_delete_expenses on public.admin_expenses for delete to authenticated
using (exists (select 1 from public.user_roles ur where ur.user_id = (select auth.uid()) and ur.role = 'owner_admin'));
grant select, insert, update, delete on public.admin_expenses to authenticated;
grant usage, select on sequence public.admin_expenses_id_seq to authenticated;
